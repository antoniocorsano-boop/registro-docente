const {test,expect}=require('@playwright/test');
const url=(process.env.NAV_CONTEXT_BASE_URL||'http://127.0.0.1:4173')+'/tests/browser/fixtures/doc01-d4c3e3-supervisor.html';
const events=page=>page.evaluate(()=>window.__doc01Supervisor.events());
test('remount: old App view retires after review, new view continues one-use authorization and checks fresh login',async({browser})=>{
 const context=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true});
 const page=await context.newPage();
 await page.goto(url);await page.getByRole('button',{name:'Esamina il recupero'}).click();
 await expect(page.getByText('Revisioni nella copia proposta')).toBeVisible();
 expect(await events(page)).toEqual(['prepare']);
 await page.getByRole('button',{name:'Disattiva vecchia vista'}).click();
 expect(await events(page)).toEqual(['prepare']);
 await page.getByRole('button',{name:'Riapri nuova vista'}).click();
 await expect(page.getByRole('button',{name:'Conferma recupero'})).toBeVisible();
 await page.getByRole('checkbox').check();
 await page.locator('#doc01-v8-consent').fill('RIPRISTINA');
 await page.getByRole('button',{name:'Conferma recupero'}).click();
 await expect(page.getByText('Non è ancora una conferma di recupero riuscito',{exact:false})).toBeVisible();
 await expect(page.getByRole('button',{name:'Verifica dopo il nuovo accesso'})).toBeVisible();
 expect((await events(page)).filter(x=>x==='commit')).toHaveLength(1);
 await page.getByRole('button',{name:'Disattiva vecchia vista'}).click();
 expect((await events(page)).filter(x=>x==='commit')).toHaveLength(1);
 await page.getByRole('button',{name:'Riapri nuova vista'}).click();
 await expect(page.getByRole('button',{name:'Verifica dopo il nuovo accesso'})).toBeVisible();
 await page.getByRole('button',{name:'Verifica dopo il nuovo accesso'}).click();
 await expect(page.getByText('Archivio riaperto e verificato.')).toBeVisible();
 expect((await events(page)).filter(x=>x==='commit')).toHaveLength(1);
 expect(await page.evaluate(()=>window.__doc01Supervisor.isDetached())).toBe(true);
 await context.close();
});
test('320px remount: disposal of a transient view neither replays grant nor shows success early',async({browser})=>{
 const context=await browser.newContext({viewport:{width:320,height:700},hasTouch:true,isMobile:true});
 const page=await context.newPage();
 await page.goto(url);await page.getByRole('button',{name:'Esamina il recupero'}).click();
 await page.getByRole('button',{name:'Disattiva vecchia vista'}).click();
 await page.getByRole('button',{name:'Riapri nuova vista'}).click();
 expect(await events(page)).toEqual(['prepare']);
 await expect(page.getByRole('button',{name:'Conferma recupero'})).toBeDisabled();
 const width=await page.evaluate(()=>({scrollWidth:document.documentElement.scrollWidth,innerWidth:window.innerWidth}));
 expect(width.scrollWidth).toBeLessThanOrEqual(width.innerWidth);
 await expect(page.getByText('Archivio riaperto e verificato.')).toHaveCount(0);
 await context.close();
});
